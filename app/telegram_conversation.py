"""Conversation pattern matching for the Telegram bot."""

import re

# ── Conversation patterns ──────────────────────────────────────────────────────
_CONVERSATION_PATTERNS = [
    # Приветствия и прощания
    r"(?:привет|здравствуй|хай|хей|йо|добрый|доброе|добрый день|добрый вечер|доброе утро|пока|до свидания|бай|чмоки)",
    # Вопросы о боте / кто ты
    r"(?:кто ты|что ты|что ты умеешь|что можешь|чем поможешь|что делаешь|зачем ты|зачем нужен|для чего ты|что за бот|что за программа|расскажи о себе|что знаешь)",
    # Благодарности
    r"(?:спасибо|благодарю|спс|сенкс|thanks|thank you|мерси|красавчик|молодец|супер|класс|отлично|крут|лучший)",
    # Вопросы о погоде / времени / жизни (не маркетплейс)
    r"(?:как дела|как ты|как поживаешь|что нового|как жизнь|как настроение|чем занят|что слышно)",
    # Жалобы / эмоции
    r"(?:скучно|хмм|ну|лол|кек|ахах|хаха|ого|вау|нет понятия|не знаю|не понял|что|ага|угу|окей|ясно|понял|ладно|норм)",
    # Вопросы не по теме
    r"(?:расскажи анекдот|шутка|юмор|загадка|игра|давай поиграем)",
]


def _is_conversation(text: str) -> bool:
    """Определяет, является ли сообщение обычным разговором, а не задачей."""
    low = text.lower().strip()
    return any(re.search(pattern, low) for pattern in _CONVERSATION_PATTERNS)


def _conversation_response(text: str) -> str:
    """Генерирует ответ на обычное сообщение."""
    low = text.lower().strip()

    # Приветствия
    if re.search(r"(?:привет|здравствуй|хай|хей|йо|добрый|доброе|добрый день|добрый вечер|доброе утро)", low):
        return (
            "Привет! Я MarketMind — слежу за ценами на маркетплейсах и готовлю карточки для Ozon.\n\n"
            "Могу: найти товар, сравнить цены, сделать карточку, найти сделки.\n"
            "Начните с /help чтобы увидеть все команды."
        )

    # Прощания
    if re.search(r"(?:пока|до свидания|бай)", low):
        return "До встречи! Если понадоблюсь — я здесь. Удачных сделок!"

    # Кто ты / что умеешь
    if re.search(
        r"(?:кто ты|что ты|что ты умеешь|что можешь|чем поможешь|что делаешь|зачем ты|расскажи о себе|что за бот)", low
    ):
        return (
            "Я MarketMind — бот для работы с маркетплейсами.\n\n"
            "Вот что я умею:\n"
            "• Слежу за ценами на Ozon, Wildberries и Yandex Market\n"
            "• Ищу товары и сравниваю цены\n"
            "• Готовлю карточки для Ozon с AI-оптимизацией\n"
            "• Нахожу лучшие сделки и скидки\n"
            "• Делаю HTML-отчёты с графиками\n\n"
            "Нажмите /help чтобы увидеть все команды."
        )

    # Благодарности
    if re.search(
        r"(?:спасибо|благодарю|спс|сенкс|thanks|thank you|мерси|красавчик|молодец|супер|класс|отлично|крут|лучший)", low
    ):
        return "Рад помочь! Если нужно что-то ещё — обращайтесь."

    # Как дела
    if re.search(r"(?:как дела|как ты|как поживаешь|что нового|как жизнь)", low):
        return "Всё отлично, работаю! Слежу за ценами и готовлю карточки.\nА у вас как дела? Чем могу помочь?"

    # Эмоции / междометия
    if re.search(r"(?:скучно|хмм|ну|лол|кек|ахах|хаха|ого|вау|ага|угу|окей|ясно|понял|ладно|норм)", low):
        return "Понял вас! Если нужно что-то сделать с товарами — я готов."

    # Шутки / игры
    if re.search(r"(?:расскажи анекдот|шутка|юмор|загадка|игра|давай поиграем)", low):
        return "Я пока не умею шутить, зато отлично ищу скидки на Ozon! \nПопробуйте /deals — найду лучшие предложения."

    # Общий fallback для разговоров
    return (
        "Я понимаю вас, но я бот для маркетплейсов — лучше всего я работаю с товарами и ценами.\n\n"
        "Попробуйте:\n"
        "• /search — найти товар\n"
        "• /add — добавить товар в мониторинг\n"
        "• /help — все команды"
    )
